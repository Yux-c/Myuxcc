/// Puts whatever is copied on the shelf: text in `.clip-texts.json` (never as `.txt` files), images as
/// `剪贴板 ….png`, copied files as copies of themselves. Copying the same thing again moves it to the top instead.
final class ClipboardWatcher {
    /// Files copied in Finder are kept as copies only up to this total size.
    static let fileSizeLimit: Int64 = 100 * 1024 * 1024
    /// Copied images larger than this (about 200 MB once decoded, more than 8K) are not kept.
    static var pixelLimit = 50_000_000
    /// Turning a copied TIFF into PNG decodes the whole image, so it happens off the main thread.
    private static let convertQueue = DispatchQueue(label: "Myuxcc.clipboard-convert", qos: .utility)
    /// Marked by password managers and similar apps (nspasteboard.org) as not to be recorded.
    static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        .map { NSPasteboard.PasteboardType($0) }

    /// Per pasteboard, a change count written by the app itself (restoring the clipboard after a
    /// paste) that is not to be recorded.
    private static var ignoredChanges: [NSPasteboard.Name: Int] = [:]

    static func ignoreCurrentContents(of pasteboard: NSPasteboard) {
        ignoredChanges[pasteboard.name] = pasteboard.changeCount
    }

    private let pasteboard: NSPasteboard
    private let storage: () -> ShelfStorage
    private var changeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general, storage: @escaping () -> ShelfStorage = { .shared }) {
        self.pasteboard = pasteboard
        self.storage = storage
        changeCount = pasteboard.changeCount
    }

    /// Checks twice a second; only a changed `changeCount` reads the pasteboard.
    func start() {
        stop()
        changeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in _ = self?.poll() }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Records the pasteboard if it changed; true when something is being added. `completion` gets the
    /// file once it is on the shelf.
    @discardableResult
    func poll(completion: ((URL?) -> Void)? = nil) -> Bool {
        guard pasteboard.changeCount != changeCount else { return false }
        changeCount = pasteboard.changeCount
        guard Self.ignoredChanges[pasteboard.name] != changeCount else { return false }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.privateTypes.contains) else { return false }
        let storage = storage()
        let stamp = ShelfDrop.timestamp()
        let done: (URL?, Bool) -> Void = { url, _ in completion?(url) }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            // Files already on the shelf (copied from it) are not copied again.
            let fresh = urls.filter { $0.deletingLastPathComponent().standardizedFileURL != storage.folder.standardizedFileURL }
            guard !fresh.isEmpty, fresh.reduce(0, { $0 + Self.size(of: $1) }) <= Self.fileSizeLimit else { return false }
            storage.importItems(fresh.map { .file($0, move: false) }) { completion?($0.first) }
            return true
        }
        let png = pasteboard.data(forType: .png)
        if let raw = png ?? pasteboard.data(forType: .tiff) {
            let isPNG = png != nil
            // An uncompressed TIFF is often far larger than its PNG, so only the pixel count limits it.
            guard !isPNG || Int64(raw.count) <= Self.fileSizeLimit else { return false }
            Self.convertQueue.async {
                let data = autoreleasepool { isPNG ? (Self.pixelCount(raw) <= Self.pixelLimit ? raw : nil) : Self.pngData(raw) }
                DispatchQueue.main.async {
                    guard let data, Int64(data.count) <= Self.fileSizeLimit else { completion?(nil); return }
                    storage.importCopy(.data(data, filename: "\(ShelvedItem.clipPrefix)\(stamp).png"), sameAs: { url in
                        url.lastPathComponent.hasPrefix(ShelvedItem.clipPrefix) && url.pathExtension == "png"
                            && Self.size(of: url) == Int64(data.count) && Self.contents(of: url) == data
                    }, completion: done)
                }
            }
            return true
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard Int64(text.utf8.count) <= Self.fileSizeLimit else { return false }
            storage.importText(text, completion: done)
            return true
        }
        return false
    }

    /// A file's bytes, memory-mapped rather than copied, for comparing with a new copy.
    static func contents(of url: URL) -> Data? {
        try? Data(contentsOf: url, options: .alwaysMapped)
    }

    /// Width × height of encoded image data, read from its header; `Int.max` when unreadable.
    static func pixelCount(_ data: Data) -> Int {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else { return .max }
        return width * height
    }

    /// Image data (TIFF and the like) re-encoded as PNG in one pass; nil when unreadable or over `pixelLimit`.
    static func pngData(_ data: Data) -> Data? {
        guard pixelCount(data) <= pixelLimit, let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImageFromSource(destination, source, 0, nil)
        return CGImageDestinationFinalize(destination) ? output as Data : nil
    }

    /// A file's size, or everything inside a folder, stopping once past the limit.
    static func size(of url: URL) -> Int64 {
        let values = try? url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
        guard values?.isDirectory == true else { return Int64(values?.fileSize ?? 0) }
        var total: Int64 = 0
        let files = FileManager.default.enumerator(at: url, includingPropertiesForKeys: [.fileSizeKey])
        while let file = files?.nextObject() as? URL, total <= fileSizeLimit {
            total += Int64((try? file.resourceValues(forKeys: [.fileSizeKey]))?.fileSize ?? 0)
        }
        return total
    }
}

/// Puts a shelf item back on the clipboard and pastes it into the app in front.
@MainActor
enum ShelfPaste {
    /// Off in the silent e2e test, which must not press ⌘V.
    static var pressesPaste = true

    /// Copied text as text, copied images as image data, every other file as the file itself
    /// (chats and mail then send it as an attachment).
    static func write(_ item: ShelvedItem, to pasteboard: NSPasteboard = ImageOutput.pasteboard) {
        pasteboard.clearContents()
        if let text = item.clipText {
            pasteboard.setString(text, forType: .string)
        } else if item.isFromClipboard, item.kind == .image, let png = try? Data(contentsOf: item.url) {
            let entry = NSPasteboardItem()
            entry.setData(png, forType: .png)
            // An uncompressed TIFF can be many times the PNG; it is made only if an app asks for it.
            let provider = TIFFProvider(png: png)
            entry.setDataProvider(provider, forTypes: [.tiff])
            TIFFProvider.current = provider
            pasteboard.writeObjects([entry])
        } else {
            pasteboard.writeObjects([item.url as NSURL])
        }
    }

    /// How long after ⌘V the clipboard is put back; the app in front must have read it by then.
    static var restoreDelay: TimeInterval = 0.8
    /// The clipboard from before a paste, waiting to be put back. A second paste before then keeps
    /// this original rather than snapshotting the first paste's item.
    private static var pendingRestore: (snapshot: PasteboardSnapshot, work: DispatchWorkItem)?

    /// Pastes the item into the front app once the shelf is out of the way, then puts the clipboard
    /// back as it was, unless something else was copied meanwhile. Without the Accessibility
    /// permission it can only copy, so the item stays on the clipboard and a toast says so.
    /// `pressKeys` stands in for ⌘V in tests.
    static func paste(_ item: ShelvedItem, pasteboard: NSPasteboard = ImageOutput.pasteboard,
                      trusted: Bool = AXIsProcessTrusted(), pressKeys: (() -> Void)? = nil) {
        guard pressesPaste || pressKeys != nil else { write(item, to: pasteboard); return }
        guard trusted else {
            write(item, to: pasteboard)
            Toast.show("已复制，按 ⌘V 粘贴（在设置里允许辅助功能后可直接粘贴）")
            return
        }
        let original = pendingRestore?.snapshot ?? PasteboardSnapshot(pasteboard)
        pendingRestore?.work.cancel()
        write(item, to: pasteboard)
        let written = pasteboard.changeCount
        let work = DispatchWorkItem {
            pendingRestore = nil
            guard pasteboard.changeCount == written else { return }
            original.restore(to: pasteboard)
            ClipboardWatcher.ignoreCurrentContents(of: pasteboard)
        }
        pendingRestore = (original, work)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            (pressKeys ?? pressCommandV)()
            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay, execute: work)
        }
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(9), keyDown: down) // V
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }
}

/// Every item on a pasteboard with the data of each of its types, to be written back later.
struct PasteboardSnapshot {
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        pasteboard.writeObjects(items.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        })
    }
}

/// Makes the TIFF version of a pasted image when an app that only reads TIFF asks for it.
private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    /// Kept until the next paste replaces it, so the pasteboard can still ask.
    static var current: TIFFProvider?
    private let png: Data

    init(png: Data) { self.png = png }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        autoreleasepool {
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { item.setData(tiff, forType: type) }
        }
    }
}
